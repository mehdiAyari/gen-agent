// Embeds the template files into src/minimal-sources.ts, so the same code renders in Node and in browsers (no file system).
// Run by "pnpm build"; a test fails when the embedded copy is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../minimal/', import.meta.url));
const sources = Object.fromEntries(
  readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(root, join(entry.parentPath, entry.name)).split(sep).join('/'))
    .sort()
    // Binary files (the Gradle Wrapper jar) are embedded in base64.
    .map((path) => [path, readFileSync(join(root, path), path.endsWith('.jar') ? 'base64' : 'utf8')]),
);

writeFileSync(
  new URL('../src/minimal-sources.ts', import.meta.url),
  `// Generated by scripts/embed-templates.js from the minimal/ directory: do not edit.\nexport const MINIMAL_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`,
);
