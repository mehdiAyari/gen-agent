import { existsSync, mkdtempSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { beforeEach, describe, expect, it } from 'vitest';

import { validateAgentYaml } from '@gen-agent/core';

import { addMcpCommand, addToolCommand, updateCommand } from './add.js';
import { newCommand } from './commands.js';
import { RecordingOutput } from './recording-output.js';

let cwd: string;
let project: string;
let out: RecordingOutput;

const at = (path: string): string => join(project, path);
const read = (path: string): string => readFileSync(at(path), 'utf8');
const javaRoot = 'src/main/java/com/example/shopbot';

beforeEach(async () => {
  cwd = mkdtempSync(join(tmpdir(), 'gen-agent-add-'));
  project = join(cwd, 'shop-bot');
  const created = await newCommand(
    {
      name: 'shop-bot',
      provider: 'ollama',
      model: 'llama3.1',
      tools: [{ name: 'refund', type: 'java', description: 'Refunds an order' }],
    },
    { cwd },
    new RecordingOutput(),
  );
  expect(created).toBe(0);
  out = new RecordingOutput();
});

describe('gen-agent add tool', () => {
  it('adds the tool to agent.yaml and its files to the project, keeping what the user wrote', async () => {
    writeFileSync(at(`${javaRoot}/tool/DefaultRefundHandler.java`), '// my implementation\n');
    writeFileSync(at('README.md'), `${read('README.md')}\nMy notes.\n`);
    const pom = read('pom.xml');

    const code = await addToolCommand(
      {
        name: 'order-status',
        type: 'http',
        url: 'https://shop.example.org/orders/{orderId}',
        description: 'Status of an order',
        params: ['orderId:string:required'],
        dir: 'shop-bot',
        cwd,
      },
      out,
    );

    expect(code).toBe(0);
    expect(validateAgentYaml(read('agent.yaml'))).toMatchObject({ ok: true });
    expect(read('agent.yaml')).toContain('- name: order-status');
    expect(existsSync(at(`${javaRoot}/generated/tool/OrderStatusTool.java`))).toBe(true);
    // The user's code is untouched; a shared file they changed gets the new version next to it.
    expect(read(`${javaRoot}/tool/DefaultRefundHandler.java`)).toBe('// my implementation\n');
    expect(read('README.md')).toContain('My notes.');
    expect(read('README.md.gen-agent-new')).toContain('order-status');
    // A shared file left as gen-agent wrote it is updated: the web client the HTTP tool needs.
    expect(read('pom.xml')).not.toBe(pom);
    expect(read('pom.xml')).toContain('spring-boot-starter-restclient');
    expect(existsSync(at('pom.xml.gen-agent-new'))).toBe(false);
    expect(statSync(at('mvnw')).mode & 0o111).not.toBe(0);
    expect(out.text()).toMatch(/README\.md\.gen-agent-new/);
  });

  it('adds a tool whose calls wait for the approval of the user', async () => {
    const created = await newCommand(
      { name: 'leave-desk', profile: 'standard', provider: 'ollama', model: 'llama3.1', tools: [] },
      { cwd },
      new RecordingOutput(),
    );
    expect(created).toBe(0);

    const options = { name: 'book-day-off', type: 'java', approval: true, dir: 'leave-desk', cwd } as const;
    expect(await addToolCommand(options, out)).toBe(0);
    expect(readFileSync(join(cwd, 'leave-desk/agent.yaml'), 'utf8')).toMatch(/approval:\n\s+required: true/);
  });

  it('refuses approval where users do not sign in, and changes nothing', async () => {
    const before = read('agent.yaml');

    expect(await addToolCommand({ name: 'cancel', type: 'java', approval: true, dir: 'shop-bot', cwd }, out)).toBe(1);
    expect(out.text()).toMatch(/approval/);
    expect(read('agent.yaml')).toBe(before);
  });

  it('refuses a name the agent already has, and changes nothing', async () => {
    const before = read('agent.yaml');

    expect(await addToolCommand({ name: 'refund', type: 'java', dir: 'shop-bot', cwd }, out)).toBe(1);
    expect(out.text()).toMatch(/error: refund is already a tool of the agent/);
    expect(read('agent.yaml')).toBe(before);
  });

  it('says where to run it when the directory is not a generated project', async () => {
    expect(await addToolCommand({ name: 'clock', type: 'java', dir: '.', cwd }, out)).toBe(1);
    expect(out.text()).toMatch(
      /error: \. is not a project generated by gen-agent: agent\.yaml and \.gen-agent\.json are needed/,
    );
  });
});

describe('gen-agent add mcp', () => {
  it('adds the MCP server to agent.yaml and the MCP client to the project', async () => {
    const code = await addMcpCommand(
      {
        name: 'files',
        package: '@modelcontextprotocol/server-filesystem',
        version: '2.0.0',
        runtime: 'node',
        sandbox: 'none',
        args: ['/srv/docs'],
        dir: 'shop-bot',
        cwd,
      },
      out,
    );

    expect(code).toBe(0);
    expect(read('agent.yaml')).toContain('package: "@modelcontextprotocol/server-filesystem"');
    expect(read('src/main/resources/application.yml')).toContain('command: npx');
    expect(read('pom.xml')).toContain('spring-ai-starter-mcp-client');
  });
});

describe('gen-agent add mcp, remote', () => {
  it('adds a remote MCP server with its token from the environment', async () => {
    const code = await addMcpCommand(
      { name: 'docs', url: 'https://mcp.example.org/mcp', tokenEnv: 'DOCS_TOKEN', dir: 'shop-bot', cwd },
      out,
    );

    expect(code).toBe(0);
    expect(read('agent.yaml')).toContain('auth: { type: bearer, env: DOCS_TOKEN }');
    expect(read('src/main/resources/application.yml')).toContain('streamable-http:');
    expect(existsSync(at(`${javaRoot}/generated/mcp/McpConfiguration.java`))).toBe(true);
  });

  it('refuses a server with neither a package nor a URL, and changes nothing', async () => {
    const before = read('agent.yaml');

    expect(await addMcpCommand({ name: 'lost', dir: 'shop-bot', cwd }, out)).toBe(1);
    expect(out.text()).toMatch(/set package \(a server the agent starts\) or url \(a remote server\)/);
    expect(read('agent.yaml')).toBe(before);
  });
});

describe('gen-agent update', () => {
  it('regenerates the project after agent.yaml is edited by hand', async () => {
    writeFileSync(
      at('agent.yaml'),
      read('agent.yaml').replace('  name: shop-bot\n', '  name: shop-bot\n  memory:\n    window: 5\n'),
    );

    expect(await updateCommand({ dir: 'shop-bot', cwd }, out)).toBe(0);
    expect(read('src/main/resources/application.yml')).toContain('window: 5');
  });
});
