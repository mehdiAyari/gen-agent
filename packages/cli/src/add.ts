import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

import { MANIFEST_PATH, planUpdate, unsupportedFeatures, validateAgentYaml, type Manifest } from '@gen-agent/core';
import { resolveOpenApi } from '@gen-agent/openapi';
import { generateProject } from '@gen-agent/templates';
import { isMap, isSeq, parseDocument, YAMLMap, YAMLSeq, type Document } from 'yaml';

import type { Output } from './commands.js';
import { VERSION } from './version.js';

interface ProjectOptions {
  /** Directory of the generated project, relative to `cwd`. */
  dir: string;
  cwd: string;
}

export interface AddToolOptions extends ProjectOptions {
  name: string;
  type: 'http' | 'java';
  url?: string;
  method?: string;
  description?: string;
  /** name:type[:required], e.g. orderId:string:required. */
  params?: string[];
}

/** A server the agent starts (package, version, runtime) or a remote one (url, its token in tokenEnv). */
export interface AddMcpOptions extends ProjectOptions {
  name: string;
  package?: string;
  version?: string;
  runtime?: 'node' | 'python';
  sandbox?: 'docker' | 'none';
  args?: string[];
  env?: string[];
  url?: string;
  tokenEnv?: string;
}

/** `gen-agent add tool <name>`: adds the tool to agent.yaml, then updates the project. */
export async function addToolCommand(options: AddToolOptions, out: Output): Promise<number> {
  return updateProject(options, out, (document) => {
    if (names(document, 'tools').includes(options.name)) return `${options.name} is already a tool of the agent`;
    const params = (options.params ?? []).map((spec) => {
      const [name = '', type = 'string', required] = spec.split(':');
      return { name, type, ...(required === 'required' ? { required: true } : {}) };
    });
    const tool = {
      name: options.name,
      type: options.type,
      ...(options.description === undefined ? {} : { description: options.description }),
      ...(options.type === 'http' && options.method !== undefined ? { method: options.method.toUpperCase() } : {}),
      ...(options.type === 'http' ? { url: options.url ?? '' } : {}),
      ...(params.length > 0 ? { params } : {}),
    };
    const node = document.createNode(tool) as YAMLMap;
    const list = node.get('params');
    if (isSeq(list)) for (const param of list.items) if (param instanceof YAMLMap) param.flow = true;
    listAt(document, 'tools').items.push(node);
    return undefined;
  });
}

/** `gen-agent add mcp <name>`: adds the MCP server to agent.yaml, then updates the project. */
export async function addMcpCommand(options: AddMcpOptions, out: Output): Promise<number> {
  return updateProject(options, out, (document) => {
    if (names(document, 'mcp').includes(options.name)) return `${options.name} is already an MCP server of the agent`;
    // Whatever is given goes to agent.yaml: core says what does not fit together.
    const node = document.createNode({
      name: options.name,
      ...(options.package === undefined ? {} : { package: options.package }),
      ...(options.version === undefined ? {} : { version: options.version }),
      ...(options.runtime === undefined ? {} : { runtime: options.runtime }),
      ...(options.sandbox === 'none' ? { sandbox: 'none' } : {}),
      ...(options.args === undefined || options.args.length === 0 ? {} : { args: options.args }),
      ...(options.env === undefined || options.env.length === 0 ? {} : { env: options.env }),
      ...(options.url === undefined ? {} : { url: options.url }),
      ...(options.tokenEnv === undefined ? {} : { auth: { type: 'bearer', env: options.tokenEnv } }),
    }) as YAMLMap;
    for (const key of ['args', 'env', 'auth']) {
      const list = node.get(key);
      if (list instanceof YAMLSeq || list instanceof YAMLMap) list.flow = true;
    }
    listAt(document, 'mcp').items.push(node);
    return undefined;
  });
}

/** `gen-agent update`: generates the project again from its agent.yaml, keeping the user's changes. */
export async function updateCommand(options: ProjectOptions, out: Output): Promise<number> {
  return updateProject(options, out, () => undefined);
}

/**
 * Applies `change` to the agent.yaml of the project, then writes the new files with the rules of planUpdate: generated
 * files rewritten, user files kept, shared files rewritten only when unchanged. Writes nothing when anything fails.
 */
async function updateProject(
  options: ProjectOptions,
  out: Output,
  change: (document: Document) => string | undefined,
): Promise<number> {
  const directory = resolve(options.cwd, options.dir);
  const configPath = join(directory, 'agent.yaml');
  const manifestPath = join(directory, MANIFEST_PATH);
  if (!existsSync(configPath) || !existsSync(manifestPath)) {
    out.error(`${options.dir} is not a project generated by gen-agent: agent.yaml and ${MANIFEST_PATH} are needed`);
    return 1;
  }

  const document = parseDocument(readFileSync(configPath, 'utf8'));
  if (document.errors.length > 0 || !isMap(document.get('agent'))) {
    out.error('agent.yaml is not valid: fix it, then run gen-agent update');
    return 1;
  }
  const refused = change(document);
  if (refused !== undefined) {
    out.error(refused);
    return 1;
  }
  const yaml = document.toString({ lineWidth: 0 });

  const result = validateAgentYaml(yaml);
  for (const warning of result.warnings) out.warn(`agent.yaml ${warning.path}: ${warning.message}`);
  if (!result.ok) {
    for (const error of result.errors) out.error(`agent.yaml ${error.path}: ${error.message}`);
    return 1;
  }
  const resolved = resolveOpenApi(result.config, (spec) => readFileSync(resolve(directory, spec), 'utf8'));
  if (!resolved.ok) {
    for (const error of resolved.errors) out.error(`agent.yaml ${error}`);
    return 1;
  }
  const unsupported = unsupportedFeatures(resolved.file);
  if (unsupported.length > 0) {
    for (const issue of unsupported) out.error(issue);
    return 1;
  }

  const files = await generateProject(resolved.file, VERSION);
  const previous = JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest;
  const actions = await planUpdate(files, previous, (path) => {
    const absolute = join(directory, path);
    return existsSync(absolute) ? readFileSync(absolute, 'utf8') : undefined;
  });

  const executable = new Set(files.filter((file) => file.executable === true).map((file) => file.path));
  const write = (path: string, content: string, mode?: number): void => {
    mkdirSync(dirname(join(directory, path)), { recursive: true });
    writeFileSync(join(directory, path), content, mode === undefined ? {} : { mode });
  };
  for (const action of actions) {
    if (action.kind === 'write') write(action.path, action.content, executable.has(action.path) ? 0o755 : undefined);
    if (action.kind === 'side') write(action.sidePath, action.content);
  }
  writeFileSync(configPath, yaml);

  const count = (predicate: (action: (typeof actions)[number]) => boolean): number => actions.filter(predicate).length;
  const sides = actions.flatMap((action) => (action.kind === 'side' ? [action.sidePath] : []));
  out.info(
    [
      `Updated ${options.dir}: ${String(count((a) => a.kind === 'write' && a.reason === 'new'))} new files, ` +
        `${String(count((a) => a.kind === 'write' && a.reason !== 'new'))} rewritten, ` +
        `${String(count((a) => a.kind === 'keep' && a.reason === 'user'))} of yours kept.`,
      ...(sides.length === 0
        ? []
        : [
            'You changed these files: merge the new version written next to each, then delete it.',
            ...sides.map((side) => `  ${side}`),
          ]),
    ].join('\n'),
  );
  return 0;
}

function names(document: Document, key: string): string[] {
  const list = document.getIn(['agent', key]);
  return isSeq(list) ? list.items.flatMap((item) => (isMap(item) ? [String(item.get('name'))] : [])) : [];
}

/** The `agent.<key>` list, created at the end of the agent when missing. */
function listAt(document: Document, key: string): YAMLSeq {
  const existing = document.getIn(['agent', key]);
  if (isSeq(existing)) return existing;
  const list = new YAMLSeq();
  document.setIn(['agent', key], list);
  return list;
}
